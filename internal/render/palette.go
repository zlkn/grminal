package render

import "image/color"

// base16 is the standard xterm ANSI palette for indices 0..15.
var base16 = [16]color.RGBA{
	{0x00, 0x00, 0x00, 0xff}, {0xcd, 0x00, 0x00, 0xff},
	{0x00, 0xcd, 0x00, 0xff}, {0xcd, 0xcd, 0x00, 0xff},
	{0x00, 0x00, 0xee, 0xff}, {0xcd, 0x00, 0xcd, 0xff},
	{0x00, 0xcd, 0xcd, 0xff}, {0xe5, 0xe5, 0xe5, 0xff},
	{0x7f, 0x7f, 0x7f, 0xff}, {0xff, 0x00, 0x00, 0xff},
	{0x00, 0xff, 0x00, 0xff}, {0xff, 0xff, 0x00, 0xff},
	{0x5c, 0x5c, 0xff, 0xff}, {0xff, 0x00, 0xff, 0xff},
	{0x00, 0xff, 0xff, 0xff}, {0xff, 0xff, 0xff, 0xff},
}

// palette256 maps a 256-color palette index to an RGBA value: 0..15 are the base
// ANSI colors, 16..231 the 6×6×6 color cube, 232..255 the grayscale ramp.
func palette256(idx uint8) color.RGBA {
	switch {
	case idx < 16:
		return base16[idx]
	case idx < 232:
		n := int(idx) - 16
		r := n / 36
		g := (n / 6) % 6
		b := n % 6
		return color.RGBA{cubeStep(r), cubeStep(g), cubeStep(b), 0xff}
	default:
		v := uint8(8 + (int(idx)-232)*10)
		return color.RGBA{v, v, v, 0xff}
	}
}

// cubeStep converts a 0..5 color-cube coordinate to an 8-bit intensity.
func cubeStep(v int) uint8 {
	if v == 0 {
		return 0
	}
	return uint8(55 + v*40)
}
